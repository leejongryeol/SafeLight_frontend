// 지도 시설 레이어의 공통 규칙 — 지도 화면(MapView)과 경로 화면(RoutePage)이 같이 쓴다.
// 두 화면이 같은 데이터를 다른 색·다른 규칙으로 그리면 사용자가 매번 다시 배워야 한다.

// 레이어별 점 색. 내 위치가 파란 원이라 CCTV 도 파랑이면 둘을 구분할 수 없었다 —
// CCTV 빨강 / 가로등 노랑 / 편의점 초록으로 나눠 파랑은 '내 위치' 전용으로 남겼었다.
//
// 치안시설(지구대·파출소 등)은 경찰을 떠올리게 파랑으로 한다. 대신 내 위치(#4285F4, 밝은 하늘색
// + 퍼지는 파동)와 헷갈리지 않게 **짙은 남색**으로 두고, 파동 없이 다른 시설과 같은 점으로 그린다.
export const LAYER_COLOR = { cctv: '#E11D48', streetLamp: '#F59E0B', store: '#10B981', police: '#1E40AF' }

// 지도 화면의 시설 점(CCTV·편의점)을 그리는 최대 지도 레벨. 이 레벨을 넘어서면
// 예전에는 마커 클러스터러가 마커를 묶었는데, 묶어도 수천 개를 만들어 붙이는 건 마찬가지라
// 느렸고 숫자 뭉치만 보여 알아볼 수도 없었다. 이제는 묶는 대신 아예 그리지 않는다.
// 레이어가 늘어도 여기만 보면 되도록 세 레이어가 같이 쓴다.
//
// 데스크탑·모바일 모두 4다. 모바일만 5로 넓혀 봤다가 되돌렸다(2026-08-07) —
// 좁은 화면이니 점도 적을 거라 생각했지만 폰 화면은 세로로 길어서(375×812) 레벨 5가
// 덮는 면적이 데스크탑 레벨 4보다 오히려 넓다. 강남역 실측:
//   모바일 L4  0.75×1.39km   CCTV 112 + 편의점  66 =  178개
//   데스크탑 L4 2.30×1.30km  CCTV 263 + 편의점 112 =  375개
//   모바일 L5  1.51×2.79km   CCTV 494 + 편의점 184 =  678개  ← 렌더에 메인스레드 455ms
// 성능도 문제였지만 결정적인 건 화면이었다. 점이 지도를 덮어 길이 안 보였다.
// 다시 넓히려면 점 크기·개수부터 손봐야 한다.
export const FACILITY_MAX_LEVEL = 4

// 가로등(보안등)만 한 단계 더 확대해야 그린다. CCTV·편의점과 같은 4로 두면 못 쓴다 —
// 보안등은 전국 184만 개로 CCTV(25만)의 7배고, 같은 도시 안에서도 동네별 편차가 크다.
// 화면 크기(위 실측치)에 좌표를 대고 세어본 개수(2026-08-21, 당시 서울 CSV 기준):
//   성북구청 L4  모바일 683 / 데스크탑 1731     L3  모바일 176 / 데스크탑 526
//   종각역    L4  모바일 259 / 데스크탑 1086     L3  모바일  66 / 데스크탑 168
// L4 에서는 가로등만으로 1,700개를 넘어 CCTV·편의점까지 합치면 2천 개가 넘는다.
// 위 표의 678개가 이미 메인스레드 455ms 였으니 L4 는 그대로 멎는다. L3 이면 가장 빽빽한
// 성북구청도 526개로 지금 데스크탑 L4(375개)와 같은 급이다.
//
// 2026-08-29 전국 공공데이터로 바뀌면서 개수는 더 늘었으니 이 상한은 그대로 둔다.
// (예전 실측에서 강남역만 유독 적었던 건 화면 탓이 아니라 강남구 원본에 좌표가 없어서였다.
//  지금은 주소를 지오코딩해 채우므로 강남도 다른 구와 비슷해진다.)
export const LAMP_MAX_LEVEL = 3

// 데스크탑만 한 단계 더 조인다(3 → 2).
//
// 위 표의 개수는 같은 레벨에서 데스크탑이 모바일의 3배쯤이다 — 가로 폭이 넓어서 같은 축척으로도
// 훨씬 넓은 면적을 덮기 때문이다. L3 에서 모바일은 176개인데 데스크탑은 526개고,
// 2026-08-29 전국 데이터로 바뀌면서 더 늘어 데스크탑에서 지도를 끌 때 눈에 띄게 밀렸다.
// 모바일은 L3 에서 문제가 없으므로 그대로 둔다 — 같이 조이면 폰에서 가로등이 거의 안 보인다.
export const lampMaxLevel = (isMobile) => (isMobile ? LAMP_MAX_LEVEL : LAMP_MAX_LEVEL - 1)

// 편의점 상호 라벨은 없앴다(2026-08-30). 많이 확대하면 상호가 붙은 알약을 띄웠는데,
// 알약 하나가 100px 가까이 돼서 지도의 상호·도로명을 덮었고 편의점이 몰린 곳에서는
// 알약끼리 겹쳐 오히려 못 읽었다. 지금은 CCTV·가로등과 같은 초록 점 하나로 통일한다 —
// 상호는 지도가 이미 제 글씨로 보여준다.

// 지도 오버레이 쌓임 순서. 숫자가 클수록 위에 온다.
//
//   가로등 1 · CCTV 2 · 편의점 3 · 치안시설 4   — 배경. 개수가 많은 것부터 아래에 깐다.
//   경로 위 안전시설 5              — 그 경로에 붙은 시설이라 배경보다 위여야 한다.
//   출발·도착 6                     — 사용자가 직접 고른 지점.
//   내 위치 9
//   검색 핀 10                      — 방금 찾은 곳이라 잠깐이라도 가리면 안 된다.
//
// **zIndex 를 안 주면 0 이다.** 그래서 내 위치·출발/도착·검색 핀이 전부 시설 점 밑에
// 묻혀 있었다. 지도에서 '내가 어디인지'와 '방금 찾은 곳'을 잃으면 나머지 정보가 다 무의미하다.
// 새 오버레이를 만들 때는 여기서 값을 가져다 쓸 것 — 숫자를 직접 적으면 또 어긋난다.
